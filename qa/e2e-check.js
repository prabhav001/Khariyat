  const assignTo = async (owner, rel) => {
    await page.fill('#f-owner', owner);
    if (rel) await radio('assign', 'rel', String(rel));
    await submit('assign');
    let msg = null;
    if (await page.isVisible('#msg-text')) { msg = await page.inputValue('#msg-text'); await closeModal(); }
    return msg;
  };
