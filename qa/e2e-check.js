  const closeModal = () => page.click('.modal-head [data-action="close-modal"]');
  const closeDrawer = async () => { if (await page.isVisible('.drawer')) await page.click('.drawer-head [data-action="close-drawer"]'); };
  const advance = () => page.click('[data-action="advance"]');
  const tab = async (t) => { await closeDrawer(); await page.click(`[data-action="tab"][data-tab="${t}"]`); };
  const text = (sel) => page.textContent(sel);
  const openFlat = async (id) => {
    await tab('register');
    if (await page.isVisible('[data-action="toggle-select"][aria-pressed="true"]')) await page.click('[data-action="toggle-select"]');
    for (const sel of ['#reg-household', '#reg-case', '#reg-next']) await page.selectOption(sel, 'all');
    if (await page.isVisible('#reg-building')) await page.selectOption('#reg-building', 'all');
    await page.fill('#reg-q', id);
    const cell = page.locator(`.cell[data-id="${id}"]`);
    if (await cell.count()) await cell.click();
    else await page.click(`.tbl [data-action="open-flat"][data-id="${id}"]`);
    await page.waitForSelector('.drawer');
  };
  const drawerAct = (action) => page.click(`.drawer [data-action="${action}"]`);
  const flat = async (id) => (await snap()).flats[id];
  const openTaskOf = async (id) => { const s = await snap(); const f = s.flats[id]; const t = f && f.taskId && s.tasks[f.taskId]; return t && t.status === 'open' ? t : null; };
  const caseOf = async (id, any) => { const s = await snap(); const list = Object.values(s.cases).filter((c) => c.flatId === id); const c = list.pop(); return c && (any || c.status === 'open') ? c : null; };
  const lastEvent = async (id, kind) => { const s = await snap(); return s.events.filter((e) => e.flatId === id && (!kind || e.kind === kind)).pop(); };
